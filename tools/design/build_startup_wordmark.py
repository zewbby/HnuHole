"""Build matching SVG and Flutter paths from Apache-2.0 Roboto Black Italic.

Requires fonttools. Pass Roboto-BlackItalic.ttf from:
https://github.com/googlefonts/roboto-2/blob/main/src/hinted/Roboto-BlackItalic.ttf
The original license is apps/mobile/assets/fonts/LICENSE-Roboto.txt.
"""

import hashlib
from pathlib import Path
import sys
import xml.etree.ElementTree as ET

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.pens.basePen import BasePen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.svgLib.path import parse_path

root = Path(__file__).resolve().parents[2]
source = Path(sys.argv[1])
brand_label = "@SpeechFUL"
brand_letters = "SpeechFUL"
digest = hashlib.sha256(source.read_bytes()).hexdigest()
if digest != "5ac072b1f16adecb9ab44891f756bd689b5760a02c0c1b14f9b7afe2f68ebbe9":
    raise ValueError("Source font differs from the approved wordmark input")
font = TTFont(source)
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
recording = DecomposingRecordingPen(glyphs)
x = 0
for character in brand_letters:
    glyph = glyphs[cmap[ord(character)]]
    glyph.draw(TransformPen(recording, (1, 0, 0, 1, x, 0)))
    x += glyph.width - font["head"].unitsPerEm * 0.025
bounds = BoundsPen(glyphs)
recording.replay(bounds)
left, bottom, right, top = bounds.bounds
text_height = 26
height = 30
scale = text_height / (top - bottom)
symbol_source = root / "apps/mobile/assets/branding/threads-symbol.svg"
symbol = DecomposingRecordingPen(glyphs)
parse_path(ET.parse(symbol_source).getroot().find("{http://www.w3.org/2000/svg}path").attrib["d"], symbol)
symbol_bounds = BoundsPen(glyphs)
symbol.replay(symbol_bounds)
symbol_left, symbol_top, symbol_right, symbol_bottom = symbol_bounds.bounds
symbol_scale = height / (symbol_bottom - symbol_top)
symbol_width = (symbol_right - symbol_left) * symbol_scale
text_left = symbol_width + 6
width = text_left + (right - left) * scale


def number(value):
    return f"{value:.3f}".rstrip("0").rstrip(".")


class OutlinePen(BasePen):
    def __init__(self):
        super().__init__(glyphs)
        self.svg = []
        self.dart = []

    def command(self, svg, dart, *points):
        values = [number(v) for point in points for v in point]
        self.svg.append(svg + " ".join(values))
        self.dart.append("    .." + dart + "(" + ", ".join(values) + ")")

    def _moveTo(self, point):
        self.command("M", "moveTo", point)

    def _lineTo(self, point):
        self.command("L", "lineTo", point)

    def _qCurveToOne(self, control, point):
        self.command("Q", "quadraticBezierTo", control, point)

    def _curveToOne(self, a, b, point):
        self.command("C", "cubicTo", a, b, point)

    def _closePath(self):
        self.svg.append("Z")
        self.dart.append("    ..close()")


outline = OutlinePen()
symbol.replay(TransformPen(outline, (symbol_scale, 0, 0, symbol_scale,
                                    -symbol_left * symbol_scale, -symbol_top * symbol_scale)))
recording.replay(TransformPen(outline, (scale, 0, 0, -scale,
                                       text_left - left * scale, top * scale + (height - text_height) / 2)))
asset = root / "apps/mobile/assets/branding/speechful-wordmark.svg"
asset.parent.mkdir(parents=True, exist_ok=True)
asset.write_text(
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {number(width)} {height}" role="img" aria-labelledby="title">\n'
    f'<title id="title">{brand_label}</title>\n'
    '<!-- Roboto Black Italic outlines, tracking -0.025em; Apache-2.0. -->\n'
    '<!-- Threads symbol: Simple Icons, CC0-1.0; see LICENSE-Simple-Icons.md. -->\n'
    f'<path fill="#000000" d="{" ".join(outline.svg)}"/>\n</svg>\n',
    encoding="utf-8",
)
dart = root / "apps/mobile/lib/src/auth/auth_wordmark_path.dart"
dart.write_text(
    '// Generated by tools/design/build_startup_wordmark.py. Do not edit paths.\n'
    '// Roboto Black Italic outlines (Apache-2.0), tracking -0.025em.\n'
    '// Threads symbol: Simple Icons (CC0-1.0), assets/branding/threads-symbol.svg.\n'
    f'// Source font SHA-256: {digest}\n'
    "import 'dart:ui';\n\n"
    f'const authWordmarkSize = Size({number(width)}, {height});\n\n'
    'final authWordmarkPath = Path()\n'
    + '\n'.join(outline.dart) + ';\n',
    encoding="utf-8",
)
print(f"Generated {asset.name} and {dart.name}: {width:.3f} x {height}")
