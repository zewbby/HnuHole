import 'dart:ui' as ui;

import 'package:flutter/material.dart';
import 'package:flutter/foundation.dart';
import 'package:flutter/services.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:hnuhole_image_viewer/image_viewer.dart';
import 'package:image_viewer_m1/component_example.dart' as example;

void main() {
  Future<void> finishSourceLoad(WidgetTester tester) async {
    for (var i = 0; i < 500; i++) {
      final controller = tester
          .widget<HnuImageViewer>(find.byType(HnuImageViewer))
          .controller;
      if (controller.status != ViewerLoadStatus.loading &&
          controller.status != ViewerLoadStatus.idle) {
        // Readiness is reported at frame end; render the enabled controls too.
        await tester.pump();
        return;
      }
      // Asset reads complete outside the widget tester's fake clock.
      await tester.runAsync(
        () => Future<void>.delayed(const Duration(milliseconds: 10)),
      );
      await tester.pump(const Duration(milliseconds: 16));
    }
    final controller = tester
        .widget<HnuImageViewer>(find.byType(HnuImageViewer))
        .controller;
    fail(
      'Source ${controller.currentItem.id} did not settle: '
      '${controller.status}, ${controller.failure}, '
      'foreground=${controller.foreground}, active=${controller.active}, '
      'platform=$defaultTargetPlatform, usage=${controller.resourceUsage}, '
      'page=${tester.widget<PageView>(find.byType(PageView)).controller?.page}.',
    );
  }

  testWidgets('iOS example stays gated independently of Android', (
    tester,
  ) async {
    debugDefaultTargetPlatformOverride = TargetPlatform.iOS;
    addTearDown(() => debugDefaultTargetPlatformOverride = null);
    await tester.pumpWidget(const example.ComponentApp());
    await tester.pumpAndSettle();
    await tester.tap(find.text('ordinary.png'));
    await tester.pumpAndSettle();
    await finishSourceLoad(tester);
    expect(
      tester
          .widget<HnuImageViewer>(find.byType(HnuImageViewer))
          .saveCoordinator,
      isNull,
    );
    expect(
      tester
          .widget<IconButton>(find.byKey(const ValueKey('viewer-save')))
          .onPressed,
      isNull,
    );
    await tester.pumpWidget(const SizedBox());
    debugDefaultTargetPlatformOverride = null;
  });

  testWidgets('16MiB valid encoded PNG is accepted and next byte is rejected', (
    tester,
  ) async {
    await tester.pumpWidget(
      const MaterialApp(
        home: example.ComponentScreen(
          initialIndex: 21,
          fixtureSet: example.ViewerFixtureSet.androidAcceptance,
        ),
      ),
    );
    await tester.pump();
    final fixtureController = tester
        .widget<HnuImageViewer>(find.byType(HnuImageViewer))
        .controller;
    final originals = await tester.runAsync(() async {
      final valid = await fixtureController.items[21].loadSource();
      final over = await fixtureController.items[22].loadSource();
      return [valid, over];
    });
    // Prepare asset IO outside the fake clock; exercise the real decoder and
    // component policy with the exact generated byte buffers.
    fixtureController.replaceItems([
      for (var i = 0; i < 2; i++)
        ViewerItem.provider(
          id: i == 0 ? 'encoded-boundary' : 'encoded-over',
          provider: originals![i].provider,
          pixelSize: originals[i].pixelSize,
        ),
    ]);
    await tester.pump();
    await finishSourceLoad(tester);
    final c = tester
        .widget<HnuImageViewer>(find.byType(HnuImageViewer))
        .controller;
    expect(c.status, ViewerLoadStatus.ready);
    expect(c.resourceUsage!.encodedBytes, 16 * 1024 * 1024);
    await tester.tap(find.byKey(const ValueKey('viewer-next')));
    await tester.pump();
    await finishSourceLoad(tester);
    expect(c.failure, ViewerFailure.resourceLimit);
    await tester.pumpWidget(const SizedBox());
  });

  testWidgets(
    'Android example owns close navigation and enables original saving',
    (tester) async {
      await tester.pumpWidget(const example.ComponentApp());
      await tester.pumpAndSettle();
      await tester.tap(find.text('ordinary.png'));
      await tester.pumpAndSettle();
      await finishSourceLoad(tester);
      final viewer = tester.widget<HnuImageViewer>(find.byType(HnuImageViewer));
      expect(viewer.controller.status, ViewerLoadStatus.ready);
      expect(
        viewer.saveCoordinator,
        isNotNull,
        reason:
            'platform=$defaultTargetPlatform, override=$debugDefaultTargetPlatformOverride',
      );
      expect(
        tester
            .widget<IconButton>(find.byKey(const ValueKey('viewer-save')))
            .onPressed,
        isNotNull,
      );
      await tester.tap(find.byKey(const ValueKey('viewer-close')));
      await tester.pumpAndSettle();
      expect(find.byType(HnuImageViewer), findsNothing);
      expect(find.text('独立图片组件'), findsOneWidget);
    },
  );

  testWidgets(
    'example source failure retries and invalidation returns to owner',
    (tester) async {
      await tester.pumpWidget(const example.ComponentApp());
      await tester.pumpAndSettle();
      await tester.tap(find.text('首次失败与手动重试'));
      await tester.pumpAndSettle();
      expect(find.text('图片加载失败'), findsOneWidget);
      await tester.tap(find.byKey(const ValueKey('viewer-retry')));
      await tester.pumpAndSettle();
      await finishSourceLoad(tester);
      expect(
        tester
            .widget<HnuImageViewer>(find.byType(HnuImageViewer))
            .controller
            .status,
        ViewerLoadStatus.ready,
      );
      await tester.tap(find.byTooltip('模拟访问失效'));
      await tester.pumpAndSettle();
      expect(find.byType(HnuImageViewer), findsNothing);
      expect(find.text('独立图片组件'), findsOneWidget);
    },
  );

  testWidgets(
    'Android replay controls decode long enough with original saving',
    (tester) async {
      await tester.pumpWidget(
        const MaterialApp(
          home: example.ComponentScreen(
            initialIndex: 1,
            fixtureSet: example.ViewerFixtureSet.galleryReplay,
          ),
        ),
      );
      await tester.pump();
      await finishSourceLoad(tester);
      final viewer = tester.widget<HnuImageViewer>(find.byType(HnuImageViewer));
      expect(viewer.saveCoordinator, isNotNull);
      expect(viewer.controller.currentItem.id, 'animation_replay_slow.webp');
      expect(viewer.controller.status, ViewerLoadStatus.ready);
      expect(viewer.controller.items.map((item) => item.id), [
        'animation.webp',
        'animation_replay_slow.webp',
        'animation_infinite.webp',
        'animation.gif',
      ]);
      await tester.runAsync(() async {
        final data = await rootBundle.load(
          'assets/fixtures/animation_replay_slow.webp',
        );
        final codec = await ui.instantiateImageCodec(data.buffer.asUint8List());
        try {
          expect(codec.frameCount, 3);
          expect(codec.repetitionCount, 1);
          for (var i = 0; i < 3; i++) {
            final frame = await codec.getNextFrame();
            expect(frame.duration, const Duration(seconds: 2));
            frame.image.dispose();
          }
        } finally {
          codec.dispose();
        }
      });
      await tester.tap(find.byKey(const ValueKey('viewer-next')));
      await tester.pump();
      await finishSourceLoad(tester);
      expect(viewer.controller.currentItem.id, 'animation_infinite.webp');
      expect(tester.takeException(), isNull);
      await tester.pumpWidget(const SizedBox());
    },
  );

  testWidgets('identity controls distinguish source and retain file timing', (
    tester,
  ) async {
    await tester.pumpWidget(
      const MaterialApp(
        home: example.ComponentScreen(
          initialIndex: 0,
          fixtureSet: example.ViewerFixtureSet.galleryIdentity,
        ),
      ),
    );
    await tester.pump();
    await finishSourceLoad(tester);
    final viewer = tester.widget<HnuImageViewer>(find.byType(HnuImageViewer));
    expect(viewer.saveCoordinator, isNotNull);
    expect(viewer.controller.currentItem.id, 'replay_identity_slow.webp');
    expect(viewer.controller.status, ViewerLoadStatus.ready);
    await tester.runAsync(() async {
      final firstPixels = <List<int>>[];
      for (final entry in [('slow', 1), ('fast', -1)]) {
        final data = await rootBundle.load(
          'assets/fixtures/replay_identity_${entry.$1}.webp',
        );
        final codec = await ui.instantiateImageCodec(data.buffer.asUint8List());
        try {
          expect(codec.frameCount, 3);
          expect(codec.repetitionCount, entry.$2);
          for (var i = 0; i < 3; i++) {
            final frame = await codec.getNextFrame();
            expect(
              frame.duration.inMilliseconds,
              entry.$1 == 'slow' ? 2000 : [80, 120, 200][i],
            );
            expect(frame.image.width, 192);
            expect(frame.image.height, 144);
            if (i == 0) {
              final pixels = await frame.image.toByteData(
                format: ui.ImageByteFormat.rawRgba,
              );
              firstPixels.add(pixels!.buffer.asUint8List().toList());
            }
            frame.image.dispose();
          }
        } finally {
          codec.dispose();
        }
      }
      expect(firstPixels[0], isNot(equals(firstPixels[1])));
    });
    await tester.tap(find.byKey(const ValueKey('viewer-next')));
    await tester.pump();
    await finishSourceLoad(tester);
    expect(viewer.controller.currentItem.id, 'replay_identity_fast.webp');
    expect(tester.takeException(), isNull);
    await tester.pumpWidget(const SizedBox());
  });

  testWidgets('closed delayed example cannot change the newly opened route', (
    tester,
  ) async {
    await tester.pumpWidget(const example.ComponentApp());
    await tester.pumpAndSettle();
    await tester.tap(find.text('延迟加载与关闭隔离'));
    await tester.pump();
    await tester.pump(const Duration(milliseconds: 400));
    final oldController = tester
        .widget<HnuImageViewer>(find.byType(HnuImageViewer))
        .controller;
    expect(oldController.status, ViewerLoadStatus.loading);
    await tester.tap(find.byKey(const ValueKey('viewer-close')));
    await tester.pumpAndSettle();
    expect(find.byType(HnuImageViewer), findsNothing);
    await tester.tap(find.text('long.png'));
    await tester.pumpAndSettle();
    await finishSourceLoad(tester);
    final currentController = tester
        .widget<HnuImageViewer>(find.byType(HnuImageViewer))
        .controller;
    expect(currentController, isNot(same(oldController)));
    await tester.pump(const Duration(seconds: 4));
    await tester.runAsync(
      () => Future<void>.delayed(const Duration(milliseconds: 30)),
    );
    await tester.pump();
    expect(find.byType(HnuImageViewer), findsOneWidget);
    expect(currentController.status, ViewerLoadStatus.ready);
    expect(currentController.active, isTrue);
    expect(currentController.currentItem.id, 'long.png');
    expect(tester.takeException(), isNull);
    await tester.tap(find.byKey(const ValueKey('viewer-close')));
    await tester.pumpAndSettle();
  });
}
